import React, { useState, useEffect } from "react";
import {
  FileText,
  Download,
  Printer,
  Search,
  Filter,
  ShieldAlert,
  SearchCheck,
  CalendarDays,
  Building2,
  Clock,
  CloudSun,
  Eye,
  X,
  FileSpreadsheet,
} from "lucide-react";
import { api } from "../services/api";
import { Report } from "../types";
import { StatusBadge } from "../components/ui/StatusBadge";

export const Reports: React.FC = () => {
  const [reports, setReports] = useState<Report[]>([]);
  const [loading, setLoading] = useState(true);
  const [typeFilter, setTypeFilter] = useState("all");
  const [searchTerm, setSearchTerm] = useState("");
  const [activeReport, setActiveReport] = useState<Report | null>(null);

  const fetchReports = async () => {
    try {
      setLoading(true);
      const data = await api.getReports();
      setReports(data);
    } catch (err) {
      console.error("Error fetching reports:", err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchReports();
  }, []);

  const handlePrint = () => {
    window.print();
  };

  const handleExportCsv = () => {
    if (reports.length === 0) return;
    const headers = ["ID", "Title", "Project", "Type", "Status", "Generated By", "Date"];
    const rows = reports.map((r) => [
      r.id,
      `"${r.title.replace(/"/g, '""')}"`,
      `"${(r.projectName || "").replace(/"/g, '""')}"`,
      r.reportType,
      r.reviewStatus,
      `"${r.generatedBy}"`,
      r.createdAt,
    ]);

    const csvContent = "data:text/csv;charset=utf-8," + [headers.join(","), ...rows.map((e) => e.join(","))].join("\n");
    const encodedUri = encodeURI(csvContent);
    const link = document.createElement("a");
    link.setAttribute("href", encodedUri);
    link.setAttribute("download", `Construction_Reports_Export_${Date.now()}.csv`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  const filtered = reports.filter((r) => {
    const matchesSearch =
      r.title.toLowerCase().includes(searchTerm.toLowerCase()) ||
      (r.projectName && r.projectName.toLowerCase().includes(searchTerm.toLowerCase()));
    const matchesType = typeFilter === "all" || r.reportType === typeFilter;
    return matchesSearch && matchesType;
  });

  const getReportIcon = (type: string) => {
    switch (type) {
      case "safety":
        return <ShieldAlert className="h-4 w-4 text-rose-500" />;
      case "crack":
        return <SearchCheck className="h-4 w-4 text-amber-500" />;
      case "planning":
        return <CalendarDays className="h-4 w-4 text-sky-500" />;
      case "valuation":
        return <Building2 className="h-4 w-4 text-emerald-500" />;
      case "weather":
        return <CloudSun className="h-4 w-4 text-sky-500" />;
      default:
        return <FileText className="h-4 w-4 text-slate-500" />;
    }
  };

  return (
    <div className="space-y-6 pb-12">
      {/* Banner */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 rounded-2xl bg-slate-900 p-5 text-white shadow-lg border border-slate-800">
        <div className="flex items-center gap-3">
          <div className="flex h-11 w-11 shrink-0 items-center justify-center rounded-xl bg-amber-500/20 text-amber-400 border border-amber-500/30">
            <FileText className="h-6 w-6" />
          </div>
          <div>
            <div className="flex items-center gap-2">
              <h1 className="text-lg font-bold">Centralized Construction Reports &amp; Exports</h1>
              <span className="rounded-md bg-amber-400/20 border border-amber-400/30 px-2 py-0.5 text-[10px] font-mono text-amber-300">
                MODULE 9
              </span>
            </div>
            <p className="text-xs text-slate-300 mt-0.5">
              Audited safety reports, crack morphology certificates, project schedules, and printable documentation.
            </p>
          </div>
        </div>

        <div className="flex items-center gap-2 self-start sm:self-auto">
          <button
            onClick={handleExportCsv}
            className="flex items-center gap-1.5 rounded-xl bg-slate-800 border border-slate-700 px-3.5 py-2 text-xs font-semibold text-slate-200 hover:bg-slate-700 transition-all cursor-pointer"
          >
            <FileSpreadsheet className="h-4 w-4 text-emerald-400" />
            <span>Export CSV</span>
          </button>
          <button
            onClick={handlePrint}
            className="flex items-center gap-1.5 rounded-xl bg-amber-500 px-3.5 py-2 text-xs font-bold text-slate-950 shadow-md shadow-amber-500/20 hover:bg-amber-400 transition-all cursor-pointer"
          >
            <Printer className="h-4 w-4" />
            <span>Print / PDF View</span>
          </button>
        </div>
      </div>

      {/* Filter and Search Bar */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 rounded-xl border border-slate-200 bg-white p-3 shadow-2xs">
        <div className="relative w-full sm:max-w-xs">
          <Search className="absolute left-3 top-2.5 h-4 w-4 text-slate-400" />
          <input
            type="text"
            value={searchTerm}
            onChange={(e) => setSearchTerm(e.target.value)}
            placeholder="Search reports by title or project..."
            className="w-full rounded-lg border border-slate-300 bg-slate-50 pl-9 pr-3 py-1.5 text-xs text-slate-800 focus:border-amber-500 focus:outline-hidden"
          />
        </div>

        <div className="flex items-center gap-2 overflow-x-auto">
          {["all", "safety", "crack", "planning", "valuation", "weather"].map((t) => (
            <button
              key={t}
              onClick={() => setTypeFilter(t)}
              className={`rounded-lg px-3 py-1 text-xs font-semibold uppercase tracking-wider transition-colors cursor-pointer ${
                typeFilter === t
                  ? "bg-slate-900 text-white"
                  : "bg-slate-100 text-slate-600 hover:bg-slate-200"
              }`}
            >
              {t}
            </button>
          ))}
        </div>
      </div>

      {/* Reports Table / List */}
      <div className="rounded-2xl border border-slate-200 bg-white p-5 shadow-2xs">
        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs">
            <thead>
              <tr className="border-b border-slate-200 bg-slate-50 text-slate-500 uppercase tracking-wider font-semibold">
                <th className="py-3 px-3">Report Title</th>
                <th className="py-3 px-3">Project Site</th>
                <th className="py-3 px-3">Type</th>
                <th className="py-3 px-3">Date</th>
                <th className="py-3 px-3">Status</th>
                <th className="py-3 px-3 text-right">Actions</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100">
              {filtered.map((rep) => (
                <tr key={rep.id} className="hover:bg-slate-50 transition-colors">
                  <td className="py-3 px-3">
                    <div className="font-bold text-slate-900">{rep.title}</div>
                    <div className="text-[11px] text-slate-500 truncate max-w-sm">{rep.summary}</div>
                  </td>
                  <td className="py-3 px-3 text-slate-700 font-medium">
                    {rep.projectName || "General Site"}
                  </td>
                  <td className="py-3 px-3">
                    <span className="flex items-center gap-1.5 capitalize font-medium text-slate-700">
                      {getReportIcon(rep.reportType)}
                      {rep.reportType}
                    </span>
                  </td>
                  <td className="py-3 px-3 text-slate-500 font-mono text-[11px]">
                    {new Date(rep.createdAt).toLocaleDateString()}
                  </td>
                  <td className="py-3 px-3">
                    <StatusBadge status={rep.reviewStatus} size="sm" />
                  </td>
                  <td className="py-3 px-3 text-right">
                    <button
                      onClick={() => setActiveReport(rep)}
                      className="rounded-lg bg-slate-100 px-2.5 py-1 text-[11px] font-semibold text-slate-700 hover:bg-slate-200 inline-flex items-center gap-1 cursor-pointer"
                    >
                      <Eye className="h-3 w-3" />
                      <span>Inspect</span>
                    </button>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>

      {/* Inspect Report Modal */}
      {activeReport && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-slate-950/70 backdrop-blur-xs p-4">
          <div className="w-full max-w-2xl rounded-2xl bg-white p-6 shadow-2xl border border-slate-200 max-h-[88vh] overflow-y-auto">
            <div className="flex items-center justify-between border-b border-slate-100 pb-3 mb-4">
              <div className="flex items-center gap-2">
                {getReportIcon(activeReport.reportType)}
                <h3 className="text-base font-bold text-slate-900">{activeReport.title}</h3>
              </div>
              <button
                onClick={() => setActiveReport(null)}
                className="rounded-lg p-1.5 text-slate-400 hover:bg-slate-100 cursor-pointer"
              >
                <X className="h-5 w-5" />
              </button>
            </div>

            <div className="space-y-4 text-xs">
              <div className="grid grid-cols-2 gap-3 bg-slate-50 p-3 rounded-xl border border-slate-100">
                <div>
                  <span className="text-[10px] uppercase font-bold text-slate-400 block">Site Project</span>
                  <span className="font-semibold text-slate-800">{activeReport.projectName}</span>
                </div>
                <div>
                  <span className="text-[10px] uppercase font-bold text-slate-400 block">Audit Date</span>
                  <span className="font-mono text-slate-800">
                    {new Date(activeReport.createdAt).toLocaleString()}
                  </span>
                </div>
              </div>

              <div>
                <span className="text-[10px] uppercase font-bold text-slate-400 block mb-1">
                  Executive Findings &amp; Summary
                </span>
                <p className="text-slate-700 leading-relaxed bg-slate-50 p-3 rounded-xl border border-slate-100">
                  {activeReport.summary}
                </p>
              </div>

              <div>
                <span className="text-[10px] uppercase font-bold text-slate-400 block mb-1">
                  Structured Report Data
                </span>
                <pre className="rounded-xl bg-slate-950 p-3 text-[11px] font-mono text-amber-300 overflow-x-auto max-h-48 border border-slate-800">
                  {JSON.stringify(activeReport.reportData, null, 2)}
                </pre>
              </div>

              <div className="rounded-xl bg-amber-50 p-3 text-[11px] text-amber-900 border border-amber-200/80 leading-relaxed">
                <strong>Certification Statement:</strong> This report integrates automated multimodal analysis and field superintendent input. Findings must be formally ratified by the licensed Project Safety Director or Structural Engineer prior to permit filing.
              </div>
            </div>

            <div className="flex items-center justify-end gap-2 border-t border-slate-100 pt-4 mt-5">
              <button
                onClick={() => setActiveReport(null)}
                className="rounded-lg bg-slate-100 px-4 py-2 font-semibold text-slate-700 hover:bg-slate-200 cursor-pointer"
              >
                Close
              </button>
              <button
                onClick={handlePrint}
                className="rounded-lg bg-slate-900 px-4 py-2 font-bold text-white hover:bg-slate-800 inline-flex items-center gap-1.5 cursor-pointer"
              >
                <Printer className="h-3.5 w-3.5 text-amber-400" />
                <span>Print Document</span>
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
